/**
 * Payload sizes one round of the ceiling ladder asks for.
 *
 * RAW bytes of the media as it would exist on disk - base64 encoding grows that by
 * 4/3 on the wire, and the request body that goes out is the encoded form. The
 * ladder climbs by roughly 4-5x per rung so a genuine threshold lands between two
 * measured rungs rather than on a guess.
 */
const INLINE_LADDER_BYTES: readonly number[] = [
  1 * 1024 * 1024,
  5 * 1024 * 1024,
  20 * 1024 * 1024,
]

/**
 * A real, decodable MP4 from an earlier run of the paid probe.
 *
 * WHY THIS IS WORTH DOING BEFORE THE LADDER RUNS. If a synthetic body is refused
 * at 1 MiB, there are two explanations - the size, or the contents - and a refusal
 * that does not say which one is not a measurement. Pairing every synthetic rung
 * with a REAL clip of the same size turns the answer into a comparison:
 *
 *   synthetic refused, real accepted  -> the threshold is about CONTENT, not size
 *   both refused                      -> the threshold is about SIZE
 *   both accepted                     -> no threshold at that rung
 *
 * That costs three more free understand calls and removes the one ambiguity this
 * step could otherwise never resolve.
 */
async function findPreviousArtifact(): Promise<string | null> {
  const root = os.tmpdir()
  try {
    const entries = await fs.readdir(root, { withFileTypes: true })
    const candidates: string[] = []
    for (const entry of entries) {
      if (!entry.isDirectory() || !entry.name.startsWith('minimax-video-probe-')) continue
      const target = path.join(root, entry.name, 'generated.mp4')
      const stat = await fs.stat(target).catch(() => null)
      if (stat !== null && stat.size > 0) candidates.push(target)
    }
    // Newest first: the most recent paid run is the one whose bytes are known good.
    candidates.sort()
    return candidates.length === 0 ? null : candidates[candidates.length - 1]!
  } catch {
    return null
  }
}

/**
 * A synthetic MP4-shaped body of exactly `size` bytes.
 *
 * Deliberately SYNTHETIC and deliberately MP4-shaped: the ftyp box at offset 4
 * makes it look like a container, so a refusal cannot be explained as "this is not
 * a video at all" on the strength of the first bytes alone. It is NOT a decodable
 * clip, which is exactly why it is paired with a real one.
 */
function syntheticMp4Body(size: number): Buffer {
  const buffer = Buffer.alloc(Math.max(size, 1))
  buffer.writeUInt32BE(0x18, 0)
  buffer.write('ftypisom', 4, 'latin1')
  buffer.fill(0x11, 12)
  return buffer
}

/**
 * A real clip grown to exactly `size` bytes by a trailing copy of itself.
 *
 * The container parser reads its own first boxes and stops, so appending bytes
 * after a complete MP4 leaves the beginning decodable while making the payload the
 * size under test. Padding is zeros rather than a repeat of the clip so the file
 * stays a plausible single stream with a trailing run of filler.
 */
function grownRealClip(base: Buffer, size: number): Buffer {
  if (base.byteLength >= size) return base.subarray(0, size)
  const out = Buffer.alloc(size)
  base.copy(out, 0)
  return out
}

interface InlineResult {
  round: number
  track: string
  rawBytes: number
  encodedBytes: number
  http: number
  code: string
  baseStatus: string
  success?: boolean
  source: string
  description: string
  error: string
}

/**
 * Classify one understand answer into the four outcomes that are NOT the same.
 *
 * A size refusal, a content refusal and a transport failure all look like "it did
 * not work"; only the first one tells us where a ceiling is. The classification is
 * by the service's own words, and the words are printed verbatim beside it so the
 * reader can disagree with the classifier.
 */
function classifyInlineFailure(result: InlineResult): string {
  const text = (result.error + ' ' + result.description).toLowerCase()
  if (result.http === 0) return 'TRANSPORT - no answer at all'
  if (/exceed|too large|size|limit|maximum|too big|413/.test(text)) return 'SIZE - the service named a size bound'
  if (/decod|invalid|unsupported|format|corrupt|not a (valid )?video/.test(text)) return 'CONTENT - the bytes were refused as media'
  if (/could not be (read|used)|could not be used as a media source/.test(text)) return 'UNSPECIFIED - the generic media-source refusal'
  return 'OTHER - read the wording'
}

/**
 * Does the answer look like the model actually SAW a video?
 *
 * MEASURED, and the reason success=true is not enough. At 5 MiB the service
 * answered success=true with a fluent description of a street dancer in front of a
 * cathedral - for a buffer of 0x11 bytes. At 20 MiB it answered success=true with
 * the model's own complaint that no video had been attached. Both are
 * success=true, and neither is evidence that the bytes were decoded.
 *
 * Two weak signals, reported as weak signals rather than as a verdict:
 * - 'source' echoing inline:<N> means the server RECEIVED N bytes;
 * - the answer naming its own inability to see anything means it received them and
 *   did not decode them.
 */
function observedVideoEvidence(result: InlineResult): string {
  const text = (result.description + ' ' + result.error).toLowerCase()
  // A description that says nothing was attached is not a description of a video,
  // whatever success says. The match is on the SERVICE's own words in both
  // languages, because the model answers in the language of the prompt.
  const denies = /没有上传|上传视频|无法看到|没有附上|no video|didn'?t (see|upload|attach)|not (able to|saw)|no (video|content) (was )?(attached|provided)/.test(text)
  // A character class rather than the usual shorthand: this file has already lost
  // one backslash to the authoring path, and a silently weakened regex is the kind
  // of bug that produces a confident wrong answer instead of an error.
  const sourceBytes = /inline:([0-9]+)/.exec(result.source)
  const received = sourceBytes === null ? null : Number(sourceBytes[1])
  if (denies) return 'NOT SEEN - the answer says no video was attached, yet success=true'
  if (received !== null && received === result.rawBytes) {
    return 'AMBIGUOUS - the server echoes inline:' + received + 'B (it received them); '
      + 'whether it decoded them is not shown by anything in this answer'
  }
  if (received !== null) {
    return 'AMBIGUOUS - source echoes ' + received + 'B, which is not the ' + result.rawBytes + 'B sent'
  }
  return 'AMBIGUOUS - no byte accounting in the answer'
}

function emitInlineRound(result: InlineResult): void {
  emit('[probe]   round ' + result.round + ' [' + result.track + '] raw=' + result.rawBytes
    + 'B encoded=' + result.encodedBytes + 'B http=' + result.http
    + ' code=' + result.code + ' base_resp=' + result.baseStatus)
  emit('[probe]     results[0].success=' + JSON.stringify(result.success)
    + ' source=' + JSON.stringify(oneLine(result.source, 120)))
  emit('[probe]     description=' + JSON.stringify(oneLine(result.description, 300)))
  emit('[probe]     error=' + JSON.stringify(oneLine(result.error, 500)))
  if (result.success !== true) {
    emit('[probe]     classification: ' + classifyInlineFailure(result))
  }
  emit('[probe]     content evidence: ' + observedVideoEvidence(result))
  emit('[probe]     ' + (result.http >= 200 && result.http < 300
    ? 'the request was NOT rejected at HTTP level - and success=true is NOT proof the bytes were decoded'
    : 'HTTP ' + result.http + ' - no answer was produced at all'))
}

/**
 * One rung: send exactly one understand call of the given size and record it.
 *
 * NEVER RETRIED. A retry after a refusal would ask the same question of a service
 * that already answered it, and after a transport failure it would spend the same
 * 20 MiB again to learn nothing new. Each rung is one call, one record.
 */
async function inlineRung(options: {
  round: number
  track: string
  region: MinimaxCodeRegion
  accessToken: string
  bytes: Buffer
  /**
   * The task-id guard, injected rather than reached for.
   *
   * The guard's state belongs to ONE run, so it lives in the test body - and a
   * module-level helper that closed over it would be reading a variable from a
   * scope it cannot see. Passing it in keeps the "one run, one guard" ownership
   * where it belongs and makes the dependency visible at the call site.
   */
  guard: (id: string) => boolean
  noteTask: (id: string, outcome: CallOutcome) => void
}): Promise<InlineResult | null> {
  const id = 'A5-r' + options.round + '-' + options.track + '-' + Math.round(options.bytes.byteLength / 1024) + 'KiB'
  if (!options.guard(id)) return null
  const data = options.bytes.toString('base64')
  emit('')
  emit('[probe] ---- ' + id + ' - one understand call, ' + options.bytes.byteLength
    + ' raw bytes -> ' + data.length + ' base64 characters')
  const outcome = await callTool({
    id: id,
    region: options.region,
    accessToken: options.accessToken,
    tool: 'videos_understand',
    body: { video_info: [{ data, prompt: '描述这个视频' }] },
    note: 'inline data at ' + (options.bytes.byteLength / (1024 * 1024)).toFixed(1) + ' MiB, sent once, never retried',
    // A 20 MiB base64 blob is not evidence; its size is.
    displayBody: '{"video_info":[{"data":"<base64 omitted: ' + data.length + ' chars>","prompt":"描述这个视频"}]}',
    timeoutMs: INLINE_TIMEOUT_MS,
  })
  options.noteTask(id, outcome)
  const results = outcome.body?.results
  const first = Array.isArray(results) ? asRecord(results[0]) : undefined
  const result: InlineResult = {
    round: options.round,
    track: options.track,
    rawBytes: options.bytes.byteLength,
    encodedBytes: data.length,
    http: outcome.status,
    code: String(outcome.body?.code ?? '(absent)'),
    baseStatus: String(baseRespOf(outcome.body).statusCode ?? '(absent)'),
    ...(typeof first?.success === 'boolean' ? { success: first.success } : {}),
    source: typeof first?.source === 'string' ? first.source : '',
    description: typeof first?.description === 'string' ? first.description : '',
    error: typeof first?.error === 'string' ? first.error : '',
  }
  emitInlineRound(result)
  return result
}

