interface QuotaRead {
  label: string
  host?: string
  /** Every row, by name, with all four count/percentage fields. */
  rows: Array<{ name: string; core: string; full: string }>
  /** Top-level keys of the document, and of the first row. */
  documentKeys: string[]
  rowKeys: string[]
  raw: string
  parsed?: unknown
}

/**
 * Read the usage document and report it WITHOUT the product's bucket filter.
 *
 * parseTokenPlanQuota() keeps only 'general' because that bucket covers chat and
 * coding and the others are separate resources. That is a display decision, not a
 * claim that the other rows do not exist - and the open question is exactly
 * whether one of them is named for video, and whether the one real generation
 * this account has run left a mark in it. So this reads the same endpoint with the
 * same headers and prints EVERY row.
 */
async function readQuotaRaw(accessToken: string, region: MinimaxCodeRegion): Promise<QuotaRead> {
  for (const host of quotaHostCandidates(region)) {
    try {
      const response = await fetchFn(tokenPlanRemainsUrl(host), {
        method: 'GET',
        headers: quotaRequestHeaders(accessToken, TOKEN_PLAN_REMAINS_PATH),
        signal: AbortSignal.timeout(QUOTA_TIMEOUT_MS),
      })
      const raw = await response.text().catch(() => '')
      let parsed: unknown
      try {
        parsed = JSON.parse(raw) as unknown
      } catch {
        parsed = undefined
      }
      const document = asRecord(parsed)
      const base = baseRespOf(parsed)
      const label = 'http=' + response.status + ' host=' + new URL(host).hostname
        + ' base_resp=' + String(base.statusCode ?? '(absent)')
        + (base.statusMsg === undefined ? '' : ' "' + oneLine(base.statusMsg, 120) + '"')
      const rows = document?.model_remains
      if (!Array.isArray(rows)) {
        return {
          label: label + ' NO model_remains',
          host,
          rows: [],
          documentKeys: document === undefined ? [] : Object.keys(document),
          rowKeys: [],
          raw,
          parsed,
        }
      }
      const out: Array<{ name: string; core: string; full: string }> = []
      let rowKeys: string[] = []
      for (const rawRow of rows) {
        const row = asRecord(rawRow)
        if (row === undefined) continue
        if (rowKeys.length === 0) rowKeys = Object.keys(row)
        const name = typeof row.model_name === 'string' && row.model_name !== '' ? row.model_name : '(unnamed)'
        // The four fields the product's card reads, printed as a compact triple so
        // a human can compare two buckets at a glance.
        const core = 'interval ' + JSON.stringify(row.current_interval_usage_count)
          + '/' + JSON.stringify(row.current_interval_total_count)
          + ' left%=' + JSON.stringify(row.current_interval_remaining_percent)
          + ' status=' + JSON.stringify(row.current_interval_status)
          + ' | weekly ' + JSON.stringify(row.current_weekly_usage_count)
          + '/' + JSON.stringify(row.current_weekly_total_count)
          + ' left%=' + JSON.stringify(row.current_weekly_remaining_percent)
          + ' status=' + JSON.stringify(row.current_weekly_status)
        out.push({ name, core, full: scalarPairs(row) })
      }
      return {
        label: label + ' rows=' + out.length,
        host,
        rows: out,
        documentKeys: document === undefined ? [] : Object.keys(document),
        rowKeys,
        raw,
        parsed,
      }
    } catch (error) {
      emit('[probe] quota read failed on one host: '
        + oneLine(error instanceof Error ? error.message : String(error), 160))
    }
  }
  return { label: 'unreachable', rows: [], documentKeys: [], rowKeys: [], raw: '' }
}

/** A bucket name that could be the video resource. */
function looksLikeVideo(name: string): boolean {
  return /video|hailuo|movie|clip|motion|gen-?video|i2v|t2v/i.test(name)
}

/**
 * Compare the product's own reader against the raw rows.
 *
 * The point is NOT to find a bug - keeping only 'general' is a documented design
 * decision. It is to establish that the reader is not silently DROPPING a bucket
 * we do not know about: if the document has four rows and the card renders one,
 * the other three have to be enumerated here or the card is hiding a resource.
 */
function compareWithProductReader(read: QuotaRead): void {
  const parsed = parseTokenPlanQuota(read.parsed)
  if (parsed === null) {
    emit('[probe]   parseTokenPlanQuota -> null (nothing usable in this document)')
    return
  }
  const general = read.rows.find((row) => row.name === 'general')
  emit('[probe]   parseTokenPlanQuota -> label=' + JSON.stringify(parsed.label)
    + ' usedPercent=' + JSON.stringify(parsed.usedPercent)
    + ' resetsAtMs=' + (parsed.resetsAtMs === undefined ? '(none)' : 'present'))
  // `windows` is optional on the contract (a document with no usable window leaves
  // it unset), so the reader-side loop has to tolerate its absence rather than
  // assume the parser always finds one.
  for (const window of parsed.windows ?? []) {
    emit('[probe]     window ' + window.key
      + ': remainingPercent=' + JSON.stringify(window.remainingPercent)
      + ' usedPercent=' + JSON.stringify(window.usedPercent)
      + ' used=' + JSON.stringify(window.used)
      + ' total=' + JSON.stringify(window.total)
      + ' unlimited=' + JSON.stringify(window.unlimited))
  }
  if (general === undefined) {
    emit('[probe]   the document has NO row named general; the reader fell back to the first row '
      + '(' + (read.rows[0]?.name ?? '(none)') + ')')
  } else {
    emit('[probe]   the general row it chose reads: ' + general.core)
  }
  const others = read.rows.filter((row) => row.name !== 'general')
  emit('[probe]   rows the reader does NOT surface: '
    + (others.length === 0 ? '(none - general is the only row)' : others.map((row) => row.name).join(', ')))
}

