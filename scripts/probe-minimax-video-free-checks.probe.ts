/**
 * Live probe: the MiniMax Code Matrix VIDEO path, measured with FREE requests only.
 *
 * WHY THIS FILE EXISTS. docs/minimax-video-generation-probe.md closed with six
 * explicit "not measured" rows. Four of them are answerable WITHOUT spending a
 * credit, because of one measured property of this gateway:
 *
 *   THE ARGUMENT VALIDATION RUNS BEFORE THE TASK IS CREATED.
 *
 * Measured: POST /mavis/api/v1/mcp/submit_video_generation with {} returns HTTP
 * 400 "invalid request: model is required" and the answer carries NO task_id. A
 * task was not created, and nothing was billed. So a request that the service is
 * GUARANTEED to refuse at validation is a free question - and the refusal text is
 * the specification, because it is the service naming its own legal values.
 *
 * THE FOUR QUESTIONS.
 *
 *   A  Does the Token Plan document carry a video resource bucket at all? The
 *      production reader (src/host/minimax-code/client.ts parseTokenPlanQuota)
 *      keeps only 'general' on purpose. This probe prints EVERY row, by name,
 *      and asks whether a real generation is visible in one of them.
 *   B  What are the legal ranges for duration / resolution / ratio? Asked by
 *      sending an ILLEGAL value and reading the service's own sentence.
 *   C  Is MiniMax-Hailuo-2.3 an accepted model? Asked with an illegal duration:
 *      a complaint about duration means the model passed validation.
 *   D  Can videos_understand read an ordinary PUBLIC http(s) URL? The earlier
 *      probe only tried a signed OSS URL (it failed). That is not the same
 *      question as "any public URL fails".
 *
 * THE GUARD IS THE DESIGN, NOT A COMMENT. Every response is walked for a
 * task_id/taskId anywhere in the envelope. The first one found sets stopAll and
 * EVERY later case is skipped - not just the failing one. A probe that keeps
 * asking after an accidental task would be billing in a loop; a probe that stops
 * and prints why leaves an honest, complete record of the one spend.
 *
 * NO VIDEO IS GENERATED by this file under any circumstance: there is no code
 * path here that submits a legal set of arguments. Every submit body in CASES
 * carries at least one value this gateway is documented to reject.
 *
 * NOTHING IDENTIFYING IS PRINTED. Token, address, account id and realUserID never
 * reach a log line. The realUserID and the account id embedded in OSS keys are
 * 18-character values that scrub()'s 32-character catch-all would NOT catch, which
 * is why the extra \uXXXX rule below exists and why this probe never resolves
 * realUserID at all. URLs are reported by SHAPE (scheme, host, segment count,
 * extension, query KEY NAMES) and never by value: a signed media URL carries its
 * own credential in the query string.
 *
 * Run: npx vitest run --config vitest.probe.config.ts probe-minimax-video-free-checks
 */
