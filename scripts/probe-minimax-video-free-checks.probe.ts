interface PublicUrlCheck {
  label: string
  reachable: boolean
  note: string
}

/**
 * Can THIS HOST fetch the candidate at all?
 *
 * This is the measurement that keeps the two failures apart. If the service
 * answers "could not be read or decoded" for a URL this machine also cannot
 * fetch, the honest conclusion is "we could not supply the bytes", NOT "the
 * service refuses public URLs". Only a URL this probe can fetch AND the service
 * cannot is evidence about the service.
 */
async function publicUrlReachability(url: string): Promise<PublicUrlCheck> {
  try {
    const response = await fetchFn(url, {
      method: 'GET',
      headers: { range: 'bytes=0-' + (PUBLIC_URL_PROBE_BYTES - 1) },
      // A public CDN commonly redirects; following is safe here because the
      // request carries no credential to replay onto whichever host answers.
      redirect: 'follow',
      signal: AbortSignal.timeout(30_000),
    }) as unknown as Response
    const bytes = new Uint8Array(await response.arrayBuffer())
    const head = Buffer.from(bytes.slice(0, 12))
    return {
      reachable: response.ok && bytes.byteLength > 0,
      label: 'http=' + response.status
        + ' content-type=' + JSON.stringify(response.headers.get('content-type') ?? '(none)')
        + ' bytes=' + bytes.byteLength
        + ' head-hex=' + head.toString('hex'),
      note: '',
    }
  } catch (error) {
    return {
      label: 'unreachable',
      reachable: false,
      note: oneLine(error instanceof Error ? error.message : String(error), 200),
    }
  }
}

