interface Step {
  label: string
  detail: string
}

const log: Step[] = []
function note(label: string, detail: string): void {
  log.push({ label, detail })
  console.log('  ' + label.padEnd(34) + detail)
}

function headers(token: string): Promise<Record<string, string>> {
  return kimiIdentityHeaders({ authorization: 'Bearer ' + token, accept: 'application/json' })
}

interface UploadResult {
  ok: boolean
  status: number
  id?: string
  note: string
}

/** POST {base}/v1/files as multipart/form-data with file + purpose. */
async function uploadFile(
  token: string,
  region: 'mainland-cn' | 'global',
  media: 'image' | 'video',
  file: string,
  mime: string,
  filename: string,
): Promise<UploadResult> {
  charge('upload', media)
  const bytes = await fs.readFile(file)
  const form = new FormData()
  form.append('file', new Blob([new Uint8Array(bytes)], { type: mime }), filename)
  form.append('purpose', media)
  const url = openAIUrl('/files', region)
  note('POST ' + new URL(url).pathname + ' (' + media + ')', bytes.length + ' bytes, purpose=' + media)
  const response = await fetch(url, {
    method: 'POST',
    headers: await headers(token),
    body: form,
    signal: AbortSignal.timeout(120_000),
  })
  const text = await response.text()
  note('  -> HTTP', String(response.status))
  if (!response.ok) return { ok: false, status: response.status, note: digestBody(text) }
  let id: string | undefined
  try {
    const parsed = JSON.parse(text) as Record<string, unknown>
    const pick = (value: unknown): string | undefined => {
      if (typeof value !== 'object' || value === null) return undefined
      const record = value as Record<string, unknown>
      if (typeof record.id === 'string' && record.id !== '') return record.id
      for (const key of ['data', 'file', 'result']) {
        const nested = pick(record[key])
        if (nested !== undefined) return nested
      }
      return undefined
    }
    id = pick(parsed)
  } catch {
    // A 2xx without JSON is a finding of its own; reported by the caller.
  }
  return { ok: true, status: response.status, ...(id === undefined ? {} : { id }), note: id === undefined ? 'no id in body: ' + scrub(text) : 'id=' + maskId(id) }
}

interface ChatResult {
  ok: boolean
  status: number
  content: string
  note: string
  ms: number
}

/** One real chat completion that references ms://<id>. */
async function referenceMedia(
  token: string,
  region: 'mainland-cn' | 'global',
  media: 'image' | 'video',
  model: string,
  fileId: string,
  question: string,
  options: { signal?: AbortSignal; label?: string } = {},
): Promise<ChatResult> {
  charge('reference', media)
  const block = media === 'image'
    ? { type: 'image_url', image_url: { url: 'ms://' + fileId } }
    : { type: 'video_url', video_url: { url: 'ms://' + fileId } }
  const body = {
    model,
    messages: [{ role: 'user', content: [{ type: 'text', text: question }, block] }],
    max_tokens: 256,
    reasoning_effort: 'low',
    stream: false,
  }
  const url = openAIUrl('/chat/completions', region)
  note((options.label ?? 'POST /v1/chat/completions') + ' [' + media + ']', 'model=' + model)
  const started = Date.now()
  const response = await fetch(url, {
    method: 'POST',
    headers: { ...(await headers(token)), 'content-type': 'application/json' },
    body: JSON.stringify(body),
    signal: options.signal ?? AbortSignal.timeout(180_000),
  })
  const ms = Date.now() - started
  const text = await response.text()
  note('  -> HTTP (' + ms + 'ms)', String(response.status))
  if (!response.ok) return { ok: false, status: response.status, content: '', note: digestBody(text), ms }
  let content = ''
  try {
    const parsed = JSON.parse(text) as Record<string, unknown>
    const choices = Array.isArray(parsed.choices) ? parsed.choices : []
    const first = choices[0] as Record<string, unknown> | undefined
    const message = (first?.message ?? {}) as Record<string, unknown>
    if (typeof message.content === 'string') content = message.content
    else if (Array.isArray(message.content)) {
      content = message.content
        .map((part) => typeof part === 'string' ? part : String((part as Record<string, unknown>)?.text ?? ''))
        .join(' ')
    }
  } catch {
    // Reported by the caller as "200 without choices".
  }
  return {
    ok: true,
    status: response.status,
    content: scrub(content, 400),
    note: content.trim() === '' ? 'empty content' : 'content <' + scrub(content, 60) + '>',
    ms,
  }
}

