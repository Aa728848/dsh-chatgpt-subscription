/** Hard caps from the task brief. They accumulate and never reset. */
const MAX_UPLOADS_PER_KIND = 2
const MAX_REFERENCES_PER_KIND = 2

const spent = {
  upload: { image: 0, video: 0 },
  reference: { image: 0, video: 0 },
}

function charge(kind: 'upload' | 'reference', media: 'image' | 'video'): void {
  spent[kind][media] += 1
  const cap = kind === 'upload' ? MAX_UPLOADS_PER_KIND : MAX_REFERENCES_PER_KIND
  if (spent[kind][media] > cap) {
    throw new Error('Probe budget exceeded (' + kind + '/' + media + '); refusing to continue.')
  }
}

