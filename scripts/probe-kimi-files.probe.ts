/** Which half of the probe this run measures; counters accumulate per run. */
const PHASE = ((): 'all' | 'image' | 'video' => {
  const found = process.argv.find((value) => value.startsWith('--phase='))
  const value = found === undefined ? '' : found.slice('--phase='.length)
  return value === 'image' || value === 'video' ? value : 'all'
})()

const IMAGE_QUESTION = 'Look at the attached image. Answer in this exact form: LEFT=<colour> RIGHT=<colour> SQUARE=<colour>. No other words.'
const IMAGE_REUSE_QUESTION = 'Look at the attached image again and list the three distinct colours you can see, comma separated.'
const VIDEO_QUESTION = 'Look at the attached video. Answer in this exact form: LEFT=<colour> RIGHT=<colour>. No other words.'

const verdict = {
  image: { upload: 'not attempted', reference: 'not attempted', evidence: 'not attempted' },
  video: { upload: 'not attempted', reference: 'not attempted', evidence: 'not attempted' },
}

async function main(): Promise<void> {
  const temp = [path.join(os.tmpdir(), 'kimi-files-probe-' + process.pid + '.png'), path.join(os.tmpdir(), 'kimi-files-probe-' + process.pid + '.mp4')]
  let token = ''
  try {
    console.log('== Kimi hosted-file reference probe ==\n')

    // 1. Credential, through the existing store API only.
    const store = new FileCredentialStore()
    const region = await resolveRegion()
    const credentials = await ensureAccessToken(store)
    token = credentials.accessToken
    const base = codingBaseUrl(credentials.region)
    console.log('region        : ' + credentials.region + ' (resolved ' + region + ')')
    console.log('base url      : ' + base + '/v1  (no credentials printed)')
    console.log('credential    : ' + store.path() + '  expires in ' + Math.max(0, Math.round((credentials.expiresAt - Date.now()) / 1000)) + 's')
    console.log('account       : ' + (credentials.userId === undefined ? '<none stored>' : maskId(credentials.userId)))
    console.log('')

    // 2. Capabilities, free.
    console.log('-- live catalog --')
    const catalog = await loadCatalog(token, credentials.region)
    const imageModel = pickImageModel(catalog)
    const videoModel = pickVideoModel(catalog)
    console.log('  image-capable : ' + catalog.filter((entry) => entry.image).map((entry) => entry.id).join(', '))
    console.log('  video-capable : ' + (catalog.filter((entry) => entry.video).map((entry) => entry.id).join(', ') || '(none declared)'))
    console.log('  chosen image  : ' + (imageModel ?? '(none)'))
    console.log('  chosen video  : ' + (videoModel ?? '(none)'))
    console.log('')

    // 3. A pre-request abort costs nothing: it proves the client cancels cleanly
    //    without a server round trip. A mid-flight cancel is NOT exercised, so
    //    the reference allowance stays available for the real questions.
    console.log('-- cancellation, pre-request (0 requests spent) --')
    const aborted = new AbortController()
    aborted.abort(new Error('probe-abort-before-send'))
    let abortOutcome = 'no error raised'
    try {
      await referenceMedia(token, credentials.region, 'image', imageModel ?? 'k3-256k', 'probe-never-sent', IMAGE_QUESTION, { signal: aborted.signal, label: 'aborted before send' })
    } catch (error) {
      abortOutcome = (error as Error).name + ': ' + scrub((error as Error).message, 120)
    } finally {
      // The charge above is refunded: nothing left the process.
      spent.reference.image -= 1
    }
    console.log('  abort before send             : ' + abortOutcome + ' (upload/reference counters unchanged)')
    console.log('')

    // 4. Image chain.
    console.log('-- image: upload --')
    const png = buildProbePng()
    await fs.writeFile(temp[0]!, png)
    console.log('  synthetic png                 : ' + png.length + ' bytes, 96x96 magenta|green + white square')
    let imageId: string | undefined
    if (imageModel === undefined) {
      verdict.image.upload = 'skipped: live catalog declared no image-capable model'
      console.log('  ' + verdict.image.upload)
    } else if (PHASE === 'video') {
      // The allowance belongs to the TASK, not to this process: a re-run that
      // re-uploaded the image would spend a slot already spent.
      verdict.image.upload = 'skipped: --phase=video (image allowance already spent)'
      console.log('  ' + verdict.image.upload)
    } else {
      const uploaded = await uploadFile(token, credentials.region, 'image', temp[0]!, 'image/png', 'probe-kimi-image.png')
      verdict.image.upload = 'HTTP ' + uploaded.status + (uploaded.ok ? ' accepted' : ' refused')
      if (!uploaded.ok) console.log('  error digest                  : ' + (uploaded.note || '<empty body>'))
      else console.log('  file id (masked)              : ' + uploaded.note)
      imageId = uploaded.id
    }
    console.log('')

    if (imageId !== undefined) {
      console.log('-- image: reference --')
      const first = await referenceMedia(token, credentials.region, 'image', imageModel!, imageId, IMAGE_QUESTION)
      verdict.image.reference = 'HTTP ' + first.status + (first.ok ? ' accepted' : ' refused')
      if (!first.ok) console.log('  error digest                  : ' + (first.note || '<empty body>'))
      else console.log('  answer                        : ' + (first.content || '<empty>'))
      const received = first.ok && /magenta|pink|purple/i.test(first.content) && /green/i.test(first.content) && /white/i.test(first.content)
      verdict.image.evidence = first.ok ? (received ? 'content matched (magenta/green/white)' : 'content did NOT match') : 'not measurable'
      console.log('')

      if (first.ok) {
        console.log('-- image: reuse the same id --')
        const again = await referenceMedia(token, credentials.region, 'image', imageModel!, imageId, IMAGE_REUSE_QUESTION, { label: 'POST /v1/chat/completions (reuse)' })
        console.log('  reuse                         : HTTP ' + again.status + (again.ok ? ' accepted' : ' refused') + (again.ok ? ' -> ' + (again.content || '<empty>') : ' -> ' + again.note))
        console.log('')
      }
    } else if (verdict.image.upload.startsWith('HTTP')) {
      console.log('-- image: reference skipped (no file id) --\n')
    }

    // 5. Video chain, only when the image chain passed.
    const imagePassed = imageId !== undefined && verdict.image.reference.endsWith('accepted') && verdict.image.evidence.startsWith('content matched')
    // --phase=video carries its own measurement: the image half was already
    // spent by an earlier run, so its absence here is not a failed gate.
    const videoGateOpen = PHASE === 'video' || imagePassed
    if (PHASE === 'image') {
      verdict.video.upload = 'skipped: --phase=image'
      verdict.video.reference = 'skipped'
      verdict.video.evidence = 'not measurable'
      console.log('-- video: skipped (--phase=image) --')
    } else if (!videoGateOpen) {
      verdict.video.upload = 'skipped: image chain did not pass, video allowance preserved'
      verdict.video.reference = 'not attempted'
      verdict.video.evidence = 'not measurable'
      console.log('-- video: skipped --')
      console.log('  reason                        : image chain did not pass; uploads/references for video stay unspent ('
        + spent.upload.video + '/' + spent.reference.video + ' used)')
    } else if (videoModel === undefined) {
      verdict.video.upload = 'skipped: live catalog declared no video-capable model'
      verdict.video.reference = 'skipped'
      verdict.video.evidence = 'not measurable'
      console.log('-- video: skipped (no video-capable model in the live catalog) --')
    } else {
      console.log('-- video: upload --')
      const mp4Problem = await buildProbeMp4(temp[1]!)
      if (mp4Problem !== '') {
        verdict.video.upload = 'skipped: could not build the synthetic clip (' + mp4Problem + ')'
        console.log('  ' + verdict.video.upload)
      } else {
        const bytes = await fs.stat(temp[1]!)
        console.log('  synthetic mp4                 : ' + bytes.size + ' bytes, 1s 160x120 cyan|magenta')
        const uploaded = await uploadFile(token, credentials.region, 'video', temp[1]!, 'video/mp4', 'probe-kimi-video.mp4')
        verdict.video.upload = 'HTTP ' + uploaded.status + (uploaded.ok ? ' accepted' : ' refused')
        if (!uploaded.ok) console.log('  error digest                  : ' + (uploaded.note || '<empty body>'))
        else console.log('  file id (masked)              : ' + uploaded.note)
        if (uploaded.id !== undefined) {
          console.log('')
          console.log('-- video: reference --')
          const first = await referenceMedia(token, credentials.region, 'video', videoModel, uploaded.id, VIDEO_QUESTION)
          verdict.video.reference = 'HTTP ' + first.status + (first.ok ? ' accepted' : ' refused')
          if (!first.ok) console.log('  error digest                  : ' + (first.note || '<empty body>'))
          else console.log('  answer                        : ' + (first.content || '<empty>'))
          const received = first.ok && /cyan|blue|teal/i.test(first.content) && /magenta|pink|purple/i.test(first.content)
          verdict.video.evidence = first.ok ? (received ? 'content matched (cyan/magenta)' : 'content did NOT match') : 'not measurable'

          // A missing-id control answers the one question a happy path cannot:
          // what does the service do with an ms:// reference that points at
          // nothing? Production needs that shape to map errors, and it costs
          // the second (last) reference slot, only after the real one worked.
          if (received) {
            console.log('')
            console.log('-- video: missing-id control --')
            const control = await referenceMedia(token, credentials.region, 'video', videoModel, 'probe-missing-file', VIDEO_QUESTION, { label: 'POST /v1/chat/completions (missing id)' })
            console.log('  missing id                    : HTTP ' + control.status + (control.ok ? ' accepted' : ' refused') + (control.ok ? ' -> ' + (control.content || '<empty>') : ' -> ' + control.note))
          }
        }
      }
    }

    // 6. Verdict.
    const liveImage = imagePassed
    const liveVideo = verdict.video.upload.endsWith('accepted') && verdict.video.reference.endsWith('accepted') && verdict.video.evidence.startsWith('content matched')
    console.log('')
    console.log('== verdict ==')
    console.log('  image : upload=' + verdict.image.upload + ' | reference=' + verdict.image.reference + ' | evidence=' + verdict.image.evidence + ' | live=' + (liveImage ? 'PASS' : 'FAIL'))
    console.log('  video : upload=' + verdict.video.upload + ' | reference=' + verdict.video.reference + ' | evidence=' + verdict.video.evidence + ' | live=' + (liveVideo ? 'PASS' : 'FAIL'))
    console.log('  spent : uploads image=' + spent.upload.image + ' video=' + spent.upload.video
      + ', references image=' + spent.reference.image + ' video=' + spent.reference.video
      + ' (caps ' + MAX_UPLOADS_PER_KIND + '/' + MAX_REFERENCES_PER_KIND + ' per kind)')
    console.log('  production integration: ' + (liveImage || liveVideo
      ? 'measured; see per-media verdict above'
      : 'NOT supported by this evidence'))
  } finally {
    if (token !== '') token = ''
    // Named files only; never a recursive delete.
    for (const file of temp) {
      try {
        await fs.unlink(file)
      } catch {
        // Already gone, or never written.
      }
    }
    console.log('\n(temp media removed by name: ' + temp.map((file) => path.basename(file)).join(', ') + ')')
  }
}

await main()
