/**
 * Live probe: does the Kimi hosted-file chain (upload -> ms://<id> reference)
 * actually work on the Kimi Code subscription gateway?
 *
 * WHY THIS FILE EXISTS. Nothing in this plugin sends a hosted file reference:
 * the Kimi Code line encodes images (and video) INLINE as base64 data URLs
 * (src/host/kimi-code/mapper.ts:724 and :742), and 'ms://' appears nowhere in
 * the repository. So "the gateway accepts POST /files and a later ms://<id>
 * reference" is a claim from Moonshot's OpenAI-compatible documentation, never
 * measured against THIS account and THIS region. This probe measures it once,
 * as a go/no-go gate for production integration.
 *
 * THE THREE STEPS RUN AT MOST TWICE EACH, AND COUNTING ACCUMULATES:
 *
 *   1. POST {base}/v1/files   multipart  (file=<bytes>, purpose=image|video)
 *   2. POST {base}/v1/chat/completions   content: [{type:'image_url'|'video_url',
 *                                         image_url|video_url:{url:'ms://<id>'}}]
 *   3. (images only, and only if step 2 succeeded) reference the SAME id a
 *      second time, to learn whether an uploaded id is reusable instead of
 *      single-use.
 *
 * There is no retry anywhere: a refusal is a finding about the link, and asking
 * the same body twice is the same refusal at twice the price. HTTP 404/405 on
 * /files is recorded and never retried (a missing route is not a transient).
 *
 * IMAGES FIRST, AND VIDEO ONLY IF THE IMAGE CHAIN PASSED. The image chain and
 * the video chain share the upload route and differ only in the purpose value
 * and the content-block name, so a broken image chain is not evidence that
 * video works - and spending the video allowance to find that out would buy no
 * decision. When the image chain fails, the video allowance stays UNSPENT and
 * this probe says so; that is a deliberate budget decision, not an oversight.
 *
 * NOTHING IDENTIFIABLE IS PRINTED. The access token never reaches a log line:
 * bullets print the endpoint without credentials, the HTTP status, a MASKED
 * file id, a one-line error digest, and the model's own answer text. The media
 * carries no metadata beyond what the encoder writes.
 *
 * SYNTHETIC MEDIA, ONE FILE PER KIND, IN THE SYSTEM TEMP DIRECTORY:
 *
 *   - the PNG is written by a minimal encoder below (no dependency, no
 *     download): 96x96 with a MAGENTA left half, a GREEN right half and a WHITE
 *     centre square. Three colours that are easy to name and hard to guess
 *     individually, so a correct answer is evidence the model saw the pixels;
 *   - the MP4 is produced by the local ffmpeg (1 s, 160x120, CYAN left band and
 *     MAGENTA right band). No video is downloaded and none is generated by any
 *     paid service.
 *
 * Both temp files are removed BY NAME at the end (never a recursive delete).
 *
 * Run: node scripts/probe-kimi-files.probe.ts
 *      (Node 24 runs the TypeScript directly; no build, no test runner.)
 */

