/** Anything token-shaped, plus e-mail addresses, is removed from printed text. */
function scrub(value: string, limit = 320): string {
  return value
    .replace(/Bearer\s+[A-Za-z0-9._~+/=-]{8,}/gi, 'Bearer <redacted>')
    .replace(/eyJ[A-Za-z0-9._-]{12,}/g, '<jwt>')
    .replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, '<email>')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, limit)
}

/** A file id, shown as "<head>..<tail>" so two ids stay distinguishable. */
function maskId(id: string): string {
  const bare = id.replace(/^ms:\/\//, '')
  if (bare.length <= 10) return bare.slice(0, 2) + '..' + bare.slice(-2)
  return bare.slice(0, 5) + '..' + bare.slice(-4)
}

/** One-line digest of an error body: JSON keys and the sentence the service sent. */
function digestBody(text: string): string {
  const raw = scrub(text, 600)
  try {
    const parsed: unknown = JSON.parse(text)
    const record = parsed as Record<string, unknown>
    const error = record.error
    const nested = typeof error === 'object' && error !== null ? error as Record<string, unknown> : undefined
    const message = nested !== undefined
      ? String(nested.message ?? nested.code ?? '')
      : typeof error === 'string' ? error : String(record.message ?? record.detail ?? '')
    const code = String(nested?.code ?? record.code ?? record.error_code ?? '')
    if (message !== '' || code !== '') return scrub('[code=' + (code || 'none') + '] ' + message)
  } catch {
    // Not JSON: fall through to the truncated text.
  }
  return raw
}

// ---------------------------------------------------------------------------
// Media: a minimal PNG encoder, and ffmpeg for the clip
// ---------------------------------------------------------------------------

const CRC_TABLE = ((): Uint32Array => {
  const table = new Uint32Array(256)
  for (let n = 0; n < 256; n += 1) {
    let c = n
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    table[n] = c >>> 0
  }
  return table
})()

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff
  for (const byte of bytes) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}

function pngChunk(type: string, data: Uint8Array): Buffer {
  const length = Buffer.alloc(4)
  length.writeUInt32BE(data.length, 0)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), Buffer.from(data)])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body), 0)
  return Buffer.concat([length, body, crc])
}

/** 96x96 RGB PNG: magenta | green halves, white centre square. */
function buildProbePng(): Buffer {
  const size = 96
  const rows: Buffer[] = []
  for (let y = 0; y < size; y += 1) {
    const row = Buffer.alloc(1 + size * 3)
    row[0] = 0 // filter: none
    for (let x = 0; x < size; x += 1) {
      const inCentre = x >= 36 && x < 60 && y >= 36 && y < 60
      const colour = inCentre
        ? [255, 255, 255]
        : x < size / 2 ? [255, 0, 170] : [0, 255, 136]
      row[1 + x * 3] = colour[0]!
      row[2 + x * 3] = colour[1]!
      row[3 + x * 3] = colour[2]!
    }
    rows.push(row)
  }
  const header = Buffer.alloc(13)
  header.writeUInt32BE(size, 0)
  header.writeUInt32BE(size, 4)
  header[8] = 8  // bit depth
  header[9] = 2  // truecolour
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk('IHDR', header),
    pngChunk('IDAT', zlib.deflateSync(Buffer.concat(rows))),
    pngChunk('IEND', new Uint8Array()),
  ])
}

/** 1 s 160x120 clip: cyan left band, magenta right band. Returns '' on success. */
function buildProbeMp4(file: string): Promise<string> {
  // Two lavfi sources hstacked rather than one drawbox: the local ffmpeg is 3.4,
  // whose drawbox has no t=fill spelling, while hstack has existed since 2.x.
  const args = [
    '-y', '-loglevel', 'error',
    '-f', 'lavfi', '-i', 'color=c=0x00E5FF:s=80x120:r=10',
    '-f', 'lavfi', '-i', 'color=c=0xFF00AA:s=80x120:r=10',
    '-t', '1',
    '-filter_complex', '[0:v][1:v]hstack=inputs=2',
    '-pix_fmt', 'yuv420p', '-c:v', 'libx264', '-profile:v', 'baseline', '-level', '3.0',
    '-movflags', '+faststart', file,
  ]
  return new Promise((resolve) => {
    const child = spawn('ffmpeg', args, { stdio: ['ignore', 'ignore', 'pipe'] })
    let stderr = ''
    child.stderr.on('data', (chunk: Buffer) => { stderr += chunk.toString('utf8') })
    child.on('error', (error) => resolve('ffmpeg could not start: ' + error.message))
    child.on('close', (code) => resolve(code === 0 ? '' : 'ffmpeg exited ' + String(code) + ': ' + scrub(stderr, 160)))
  })
}

