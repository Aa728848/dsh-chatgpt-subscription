interface CatalogEntry {
  id: string
  image: boolean
  video: boolean
}

async function loadCatalog(token: string, region: 'mainland-cn' | 'global'): Promise<CatalogEntry[]> {
  const response = await fetch(openAIUrl('/models', region), {
    headers: await headers(token),
    signal: AbortSignal.timeout(45_000),
  })
  const text = await response.text()
  note('GET /v1/models', 'HTTP ' + response.status)
  if (!response.ok) {
    console.log('    body: ' + digestBody(text))
    return []
  }
  const parsed = JSON.parse(text) as unknown
  const data = Array.isArray(parsed) ? parsed : (parsed as Record<string, unknown>).data
  if (!Array.isArray(data)) return []
  return data.flatMap((entry) => {
    if (typeof entry !== 'object' || entry === null) return []
    const record = entry as Record<string, unknown>
    if (typeof record.id !== 'string') return []
    return [{
      id: record.id,
      image: record.supports_image_in === true || record.supports_image_url_in === true,
      video: record.supports_video_in === true,
    }]
  })
}

/** Cheapest image-capable model: registry quota multiplier first, then order. */
function pickImageModel(catalog: CatalogEntry[]): string | undefined {
  const capable = catalog.filter((entry) => entry.image)
  const ranked = capable
    .map((entry) => ({ entry, cost: kimiCodeModelDef(entry.id)?.quotaMultiplier ?? 99 }))
    .sort((left, right) => left.cost - right.cost)
  return ranked[0]?.entry.id
}

function pickVideoModel(catalog: CatalogEntry[]): string | undefined {
  const capable = catalog.filter((entry) => entry.video)
  const ranked = capable
    .map((entry) => ({ entry, cost: kimiCodeModelDef(entry.id)?.quotaMultiplier ?? 99 }))
    .sort((left, right) => left.cost - right.cost)
  return ranked[0]?.entry.id
}

